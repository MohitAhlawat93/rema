create table if not exists public.witness_lema_knowledge (
  id bigint generated by default as identity primary key,
  question text not null,
  answer text not null,
  keywords text[] not null default '{}',
  href text not null default '',
  published boolean not null default true,
  sort_order integer not null default 0,
  search_document tsvector not null default ''::tsvector,
  updated_at timestamptz not null default now()
);

alter table public.witness_lema_knowledge enable row level security;
revoke all on table public.witness_lema_knowledge from anon, authenticated;
grant select on table public.witness_lema_knowledge to anon, authenticated;
create policy "published knowledge is readable"
on public.witness_lema_knowledge for select
to anon, authenticated
using (published = true);
create index if not exists witness_lema_knowledge_search_idx on public.witness_lema_knowledge using gin (search_document);

create or replace function public.update_witness_lema_search_document()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.search_document := to_tsvector('english', coalesce(new.question, '') || ' ' || coalesce(new.answer, '') || ' ' || coalesce(array_to_string(new.keywords, ' '), ''));
  return new;
end;
$$;

drop trigger if exists witness_lema_search_document_trigger on public.witness_lema_knowledge;
create trigger witness_lema_search_document_trigger
before insert or update of question, answer, keywords on public.witness_lema_knowledge
for each row execute function public.update_witness_lema_search_document();

create or replace function public.search_witness_lema_knowledge(query_text text, match_count integer default 3)
returns table (question text, answer text, href text, rank real)
language sql
stable
security invoker
set search_path = ''
as $$
  select k.question, k.answer, k.href,
    ts_rank_cd(k.search_document, websearch_to_tsquery('english', left(query_text, 400))) as rank
  from public.witness_lema_knowledge as k
  where k.published
    and k.search_document @@ websearch_to_tsquery('english', left(query_text, 400))
  order by rank desc, k.sort_order asc
  limit least(greatest(match_count, 1), 5);
$$;

revoke all on function public.search_witness_lema_knowledge(text, integer) from public;
grant execute on function public.search_witness_lema_knowledge(text, integer) to anon, authenticated;
